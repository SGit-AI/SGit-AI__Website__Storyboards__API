def bars(sizes):
    """The release's own sizes, from its manifest: the drawing, the fonts, Rough.js and everything else."""
    kb = lambda n: round(n / 1000)
    fonts = sum(v for k, v in sizes.items() if k.startswith("fonts/"))
    groups = [("storyboard.js", sizes.get("storyboard.js", 0)), ("fonts", fonts), ("rough.js", sizes.get("vendor/rough-4.6.6.js", 0))]
    rest = sum(sizes.values()) - sum(v for _, v in groups)
    return [{"label": l, "value": kb(v), "shown": f"{kb(v)} KB"} for l, v in groups] + [{"label": "the rest", "value": kb(rest), "shown": f"{kb(rest)} KB", "colour": "#7c3aed"}]


